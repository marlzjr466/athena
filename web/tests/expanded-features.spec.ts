import { test, expect, type Page } from '@playwright/test';
async function choose(page: Page, label: string, option: string) {
  await page.getByRole('combobox', { name: label, exact: true }).click();
  await page.getByRole('option', { name: option, exact: true }).click();
  await expect(page.getByRole('combobox', { name: label, exact: true })).toContainText(option);
}
test('Athena custom selects support keyboard, dismissal and all original fields', async ({ page }) => {
  await page.goto('/#features');
  await expect(page.locator('.scene-stage')).toHaveAttribute('data-ready', 'true');
  await expect(page.locator('select')).toHaveCount(0);
  const model = page.getByRole('combobox', { name: 'AI model', exact: true });
  await model.focus();
  await model.press('ArrowDown');
  await expect(model).toHaveAttribute('aria-expanded', 'true');
  await model.press('End');
  await model.press('Enter');
  await expect(model).toContainText('Online · Anthropic');
  await expect(model).toBeFocused();
  await model.press('ArrowDown');
  await model.press('Escape');
  await expect(page.getByRole('listbox')).toHaveCount(0);
  await model.click();
  await page.locator('#features h2').click();
  await expect(page.getByRole('listbox')).toHaveCount(0);
  await choose(page, 'Reasoning effort', 'Quick');
  await choose(page, 'Sample attachment', 'interface.png');
  await page.locator('#personalization').scrollIntoViewIfNeeded();
  await choose(page, 'Personality', 'Bright & cheerful');
  await page.locator('#voice').scrollIntoViewIfNeeded();
  await choose(page, 'Browser voice', 'System default');
  await page.locator('#meet').scrollIntoViewIfNeeded();
  const expressions = page.getByRole('combobox', { name: 'More expressions' });
  await expressions.focus(); await expressions.press('b'); await expressions.press('l'); await expressions.press('Enter');
  await expect(expressions).toContainText('Blush');
  await expressions.click();
  await expect(page.getByRole('option', { name: /^(Sit|Flip|Flight|Land|Turn)( |$)/ })).toHaveCount(0);
  await expressions.press('Tab');
  await expect(page.getByRole('listbox')).toHaveCount(0);
});
