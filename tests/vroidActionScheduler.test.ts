import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { VroidActionScheduler } from '../electron/main/vroidActionScheduler'
import { VROID_ACTION_IDS, VROID_RANDOM_IDS, type VroidActionId } from '../shared/vroidActions'

beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(10000) })
afterEach(() => vi.useRealTimers())
function setup() {
  const context = { selected: true, blocked: false, random: true, enabled: [...VROID_RANDOM_IDS], task: undefined as undefined | { id: VroidActionId; key: string; loop: boolean } }
  const changed = vi.fn()
  const scheduler = new VroidActionScheduler({ context: () => context, changed }, Date.now, () => 0)
  scheduler.register(VROID_ACTION_IDS.map(id => ({ id, duration: id === 'idle' ? 5 : 2 })))
  return { scheduler, context, changed }
}
describe('one authoritative VRoid scheduler', () => {
  it('cycles after exactly 3 seconds following each fade, never repeats when alternatives exist', () => {
    const { scheduler } = setup()
    vi.advanceTimersByTime(3219)
    expect(scheduler.session?.action).toBe('idle')
    vi.advanceTimersByTime(1)
    expect(scheduler.session?.action).toBe('angry')
    expect(scheduler.session?.loop).toBe(false)
    vi.advanceTimersByTime(2000)
    expect(scheduler.session?.action).toBe('idle')
    vi.advanceTimersByTime(3220)
    expect(scheduler.session?.action).toBe('blush')
    scheduler.dispose()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('registers all 20 and permits each enabled action, reserving Idle as a loop', () => {
    const { scheduler } = setup()
    expect(scheduler.snapshot().clips).toHaveLength(20)
    for (const id of VROID_ACTION_IDS) {
      expect(scheduler.trigger(id).ok).toBe(true)
      expect(scheduler.session?.action).toBe(id)
      expect(scheduler.session?.loop).toBe(id === 'idle')
    }
    scheduler.dispose()
  })
  it('honors disabled clips, manual playback, missing clips and random preference', () => {
    const { scheduler, context } = setup()
    context.enabled = ['bow']; context.random = false; scheduler.reconcile()
    expect(scheduler.trigger('clapping').ok).toBe(false)
    expect(scheduler.trigger('bow').ok).toBe(true)
    vi.advanceTimersByTime(2000)
    expect(scheduler.session?.action).toBe('idle')
    vi.advanceTimersByTime(10000)
    expect(scheduler.session?.action).toBe('idle')
    scheduler.dispose()
    const missing = new VroidActionScheduler({ context: () => context, changed: () => {} })
    expect(missing.trigger('bow').ok).toBe(false)
    missing.dispose()
  })
  it('preempts random gestures for work and waits a fresh idle interval after interruption', () => {
    const { scheduler, context } = setup()
    vi.advanceTimersByTime(3220)
    context.task = { id: 'thinking', key: 'task-1', loop: true }; scheduler.reconcile()
    expect(scheduler.session?.action).toBe('thinking')
    expect(scheduler.trigger('bow').ok).toBe(false)
    vi.advanceTimersByTime(20000)
    context.task = undefined; context.blocked = true; scheduler.reconcile()
    expect(scheduler.session?.action).toBe('idle')
    vi.advanceTimersByTime(10000)
    context.blocked = false; scheduler.reconcile()
    vi.advanceTimersByTime(3219)
    expect(scheduler.session?.action).toBe('idle')
    vi.advanceTimersByTime(1)
    expect(scheduler.session?.source).toBe('random')
    scheduler.dispose()
  })
  it('owns a separate floating voice lane and resumes the randomized cycle after cancellation or completion', () => {
    const { scheduler } = setup()
    vi.advanceTimersByTime(3220)
    scheduler.setVoicePhase('listening')
    expect(scheduler.snapshot().voiceSession?.phase).toBe('listening')
    expect(scheduler.snapshot().voiceSession?.previousAction?.action).toBe('angry')
    const firstSequence = scheduler.snapshot().voiceSession!.sequence
    scheduler.setVoicePhase('thinking')
    expect(scheduler.snapshot().voiceSession).toMatchObject({ phase: 'thinking', previous: { phase: 'listening' } })
    scheduler.setVoicePhase('talking')
    expect(scheduler.snapshot().voiceSession).toMatchObject({ phase: 'talking', previous: { phase: 'thinking' } })
    expect(scheduler.snapshot().voiceSession!.sequence).toBeGreaterThan(firstSequence)
    vi.advanceTimersByTime(15_000)
    expect(scheduler.session?.action).toBe('idle')
    scheduler.setVoicePhase(null)
    expect(scheduler.snapshot().voiceSession).toBeNull()
    expect(scheduler.snapshot().session?.previousVoice?.phase).toBe('talking')
    vi.advanceTimersByTime(3219)
    expect(scheduler.session?.action).toBe('idle')
    vi.advanceTimersByTime(1)
    expect(scheduler.session?.source).toBe('random')
    scheduler.dispose()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('does not replay completed task notifications or reset playback when a second renderer reports', () => {
    const { scheduler, context } = setup()
    context.task = { id: 'clapping', key: 'completed-1', loop: false }; scheduler.reconcile()
    const session = scheduler.session
    scheduler.register([{ id: 'idle', duration: 5 }, { id: 'clapping', duration: 2 }])
    expect(scheduler.session).toBe(session)
    vi.advanceTimersByTime(2000)
    scheduler.reconcile()
    expect(scheduler.session?.action).toBe('idle')
    context.selected = false; scheduler.reconcile()
    expect(scheduler.session).toBeNull()
    expect(vi.getTimerCount()).toBe(0)
    context.selected = true; context.task = undefined; scheduler.reconcile()
    expect(scheduler.session?.action).toBe('idle')
    scheduler.dispose()
  })
})
