import { afterEach, describe, expect, it } from 'vitest'
import { access, mkdtemp, readFile, rm, symlink, unlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { AvatarModelRepository, validateVrmBytes } from '../electron/main/avatarModelRepository'
import { avatarName, isVrmAvatar, validateModelName } from '../shared/avatarModels'
import { mergeSettings, defaultSettings, restoreSettings } from '../shared/settings'

const directories: string[] = []
async function repository() { const root = await mkdtemp(join(tmpdir(), 'athena-avatar-test-')); directories.push(root); return { root, repo: new AvatarModelRepository(root) } }
const source = resolve('src/assets/avatars/vroid-athena/model.vrm')
const png = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLttAAAAABJRU5ErkJggg=='
afterEach(async () => { await Promise.all(directories.splice(0).map(root => rm(root, { recursive: true, force: true }))) })

describe('imported model names and identities', () => {
  it('trims Unicode names and rejects empty, oversized, hidden-control and duplicate names', () => {
    expect(validateModelName('  ルナ — Nova 2  ', [])).toBe('ルナ — Nova 2')
    for (const name of ['', '  ', 'x'.repeat(61), 'Nova\u202e', 'athena', 'Ａｔｈｅｎａ']) expect(() => validateModelName(name, [])).toThrow()
    expect(() => validateModelName('luna', [{ id: 'one', name: 'Luna' }])).toThrow(/already/)
    expect(validateModelName('Luna', [{ id: 'one', name: 'Luna' }], 'one')).toBe('Luna')
  })
  it('copies the actual VRM, persists an independent ID/name and renames without changing assets or settings', async () => {
    const { root, repo } = await repository()
    const picked = repo.pick(source)
    expect(picked.suggestedName).toBe('model')
    expect(repo.list()).toHaveLength(0)
    const model = await repo.import(picked.token, ' Luna ')
    expect(model.importStatus).toBe('processing')
    expect(model.configuration.version).toBe('1.0')
    expect(model.id).toMatch(/^imported-/)
    expect(model.modelPath).not.toContain('Luna')
    expect(Buffer.from(await repo.read(model.id)).equals(await readFile(source))).toBe(true)
    await repo.finish(model.id, png, [{ id: 'idle', duration: 2 }, { id: 'bow', duration: 3 }, { id: 'jump', error: 'incompatible' }], 1.2)
    const ready = repo.get(model.id)
    expect(ready.enabledActions).toEqual(['bow'])
    const renamed = repo.rename(model.id, 'Mia')
    expect(renamed.modelPath).toBe(model.modelPath)
    expect(renamed.compatibleAnimations).toEqual(ready.compatibleAnimations)
    const restored = new AvatarModelRepository(root).get(model.id)
    expect(restored.name).toBe('Mia')
    expect(restored.thumbnail).toBe(png)
    expect(restored.importStatus).toBe('ready')
    const saved = mergeSettings(defaultSettings, { avatarVariant: model.id })
    expect(restoreSettings(JSON.parse(JSON.stringify(saved))).avatarVariant).toBe(model.id)
    expect(avatarName(model.id, [restored])).toBe('Mia')
    expect(isVrmAvatar(model.id)).toBe(true)
  })
  it('keeps multiple copies independent and guards pick tokens, file formats, names and paths', async () => {
    const { repo } = await repository()
    const first = await repo.import(repo.pick(source).token, 'Luna')
    const second = await repo.import(repo.pick(source).token, 'Nova')
    expect(first.id).not.toBe(second.id)
    expect(() => repo.rename(second.id, 'Luna')).toThrow(/already/)
    expect(() => repo.pick('/tmp/not-a-model.glb')).toThrow(/.vrm/)
    await expect(repo.import('unknown', 'Rin')).rejects.toThrow(/expired/)
    await expect(repo.read('../settings.json')).rejects.toThrow()
    await expect(repo.finish(first.id, png, [{ id: 'bow', duration: 1 }], 1)).rejects.toThrow(/Idle/)
    await expect(repo.finish(first.id, 'not-a-png', [{ id: 'idle', duration: 1 }], 1)).rejects.toThrow(/thumbnail/)
  })
  it('retains named failed cards and converts interrupted imports to retryable errors after reload', async () => {
    const { root, repo } = await repository()
    const bad = join(root, 'invalid.vrm'); await writeFile(bad, 'not VRM')
    const failed = await repo.import(repo.pick(bad).token, 'Invalid model')
    expect(failed.importStatus).toBe('error'); expect(failed.name).toBe('Invalid model')
    expect(failed.importError).toMatch(/Invalid/)
    const retried = await repo.replaceFailedSource(failed.id, source)
    expect(retried.id).toBe(failed.id)
    expect(retried.name).toBe('Invalid model')
    expect(retried.importStatus).toBe('processing')
    repo.interrupt()
    expect(repo.get(retried.id).importError).toMatch(/reloaded/)
    const good = await repo.import(repo.pick(source).token, 'Good model')
    expect(new AvatarModelRepository(root).get(good.id).importStatus).toBe('error')
  })
  it('preserves corrupt registry bytes instead of crashing or overwriting existing data', async () => {
    const { root } = await repository()
    await writeFile(join(root, 'registry.json'), 'broken registry')
    const repo = new AvatarModelRepository(root)
    expect(repo.loadError).toMatch(/preserved/)
    expect(() => repo.pick(source)).toThrow(/registry/)
    expect(await readFile(join(root, 'registry.json'), 'utf8')).toBe('broken registry')
  })
  it('does not follow a substituted symlink outside model storage', async () => {
    const { root, repo } = await repository()
    const model = await repo.import(repo.pick(source).token, 'Luna')
    const path = join(root, model.modelPath)
    await unlink(path); await symlink(source, path)
    await expect(repo.read(model.id)).rejects.toThrow(/escapes/)
  })
  it('completely deletes only the selected imported model and preserves the source and other models', async () => {
    const { root, repo } = await repository()
    const selected = await repo.import(repo.pick(source).token, 'Delete me')
    const other = await repo.import(repo.pick(source).token, 'Keep me')
    expect(() => repo.delete(selected.id)).toThrow(/finish/)
    await repo.finish(selected.id, png, [{ id: 'idle', duration: 2 }], 1)
    repo.delete(selected.id)
    expect(repo.list().map(m => m.id)).toEqual([other.id])
    await expect(access(join(root, selected.id))).rejects.toThrow()
    expect(new AvatarModelRepository(root).list().map(m => m.id)).toEqual([other.id])
    expect(Buffer.from(await repo.read(other.id)).equals(await readFile(source))).toBe(true)
    expect(() => repo.delete('vroid-athena')).toThrow()
    expect(() => repo.delete('../registry.json')).toThrow()
  })
  it('rejects deleting a substituted storage directory without following its symlink', async () => {
    const { root, repo } = await repository()
    const model = await repo.import(repo.pick(source).token, 'Protected')
    repo.update(model.id, { importStatus: 'error' })
    await rm(join(root, model.id), { recursive: true })
    await symlink(resolve('src/assets/avatars/vroid-athena'), join(root, model.id))
    expect(() => repo.delete(model.id)).toThrow(/not authorized/)
    expect(repo.get(model.id).name).toBe('Protected')
    await expect(access(source)).resolves.toBeUndefined()
  })
  it('updates a portrait without resetting model actions, identity, or name', async () => {
    const { root, repo } = await repository()
    const model = await repo.import(repo.pick(source).token, 'Portrait')
    await repo.finish(model.id, png, [{ id: 'idle', duration: 2 }, { id: 'bow', duration: 3 }], 1)
    repo.update(model.id, { enabledActions: [] })
    const refreshed = await repo.saveThumbnail(model.id, png)
    expect(refreshed.enabledActions).toEqual([])
    expect(refreshed.name).toBe('Portrait')
    expect(refreshed.thumbnailVersion).toBe(2)
    expect(new AvatarModelRepository(root).get(model.id).thumbnailVersion).toBe(2)
  })
  it('validates real VRM data and rejects malformed containers and remote texture references', async () => {
    const bytes = await readFile(source)
    expect(validateVrmBytes(bytes)).toBe('1.0')
    expect(() => validateVrmBytes(bytes.subarray(0, 100))).toThrow()
    const length = bytes.readUInt32LE(12)
    const json = JSON.parse(bytes.subarray(20, 20 + length).toString())
    json.images[0].uri = 'https://example.com/private.png'
    let metadata = Buffer.from(JSON.stringify(json)); metadata = Buffer.concat([metadata, Buffer.alloc((4 - metadata.length % 4) % 4, 32)])
    const header = Buffer.from(bytes.subarray(0, 20)); header.writeUInt32LE(metadata.length, 12)
    const invalid = Buffer.concat([header, metadata, bytes.subarray(20 + length)]); invalid.writeUInt32LE(invalid.length, 8)
    expect(() => validateVrmBytes(invalid)).toThrow(/External/)
  })
})
