import { test, expect, _electron as electron } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { tmpdir } from 'node:os'

test('branch popup uses real IPC and Git, preserves changes, synchronizes externally and survives restart', async () => {
  const profile = await mkdtemp(join(tmpdir(), 'athena-branch-desktop-')), project = join(profile, 'project')
  await mkdir(project)
  const git = (...args: string[]) => execFileSync('git', args, { cwd: project, encoding: 'utf8', env: { ...process.env, GIT_AUTHOR_NAME: 'Fixture', GIT_AUTHOR_EMAIL: 'test@example.test', GIT_COMMITTER_NAME: 'Fixture', GIT_COMMITTER_EMAIL: 'test@example.test' } })
  git('init', '-b', 'main'); await writeFile(join(project, 'source.txt'), 'fixture')
  const conflictFiles = Array.from({ length: 12 }, (_, index) => `long-project-source-path-for-branch-conflict-${index}.ts`)
  for (const file of conflictFiles) await writeFile(join(project, file), 'fixture')
  git('add', '.'); git('commit', '-m', 'fixture'); git('branch', 'feature/two')
  git('switch', '-c', 'feature/one')
  for (const file of conflictFiles) await writeFile(join(project, file), 'other branch content')
  git('add', '.'); git('commit', '-m', 'conflicting fixture'); git('switch', 'main')
  for (const file of conflictFiles) await writeFile(join(project, file), 'preserved local content')
  for (let index = 0; index < 18; index++) git('branch', `maintenance/branch-${index}`)
  await writeFile(join(project, 'source.txt'), 'preserved dirty content'); await writeFile(join(project, 'untracked.txt'), 'preserved untracked')
  await writeFile(join(profile, 'settings.json'), JSON.stringify({ aiMode: 'unconfigured', strictOffline: true, voiceEnabled: false, floatingEnabled: false, randomActions: false, randomMovement: false, webAccess: { enabled: false, searxngAutoStart: false } }))
  const launch = () => electron.launch({ args: ['.'], env: { ...process.env, ATHENA_TEST_DATA: profile } })
  let app = await launch()
  try {
    await expect.poll(() => app.windows().some(page => page.url().includes('surface=control'))).toBe(true)
    let control = app.windows().find(page => page.url().includes('surface=control'))!
    await control.setViewportSize({ width: 1100, height: 760 })
    await app.evaluate(({ dialog }, project) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [project] }) }, project)
    await control.evaluate(async () => {
      await window.athena!.setPermissionEnabled({ permission: 'personalFiles', enabled: true })
      const chat = await window.athena!.getChat()
      await window.athena!.chatContext({ action: 'connect', sessionId: chat.sessionId! })
    })
    await control.getByRole('button', { name: 'Conversation', exact: true }).click()
    await control.getByRole('button', { name: 'Git branch: main' }).click()
    const menu = control.getByRole('dialog', { name: 'Project branches' })
    await expect(menu).toBeVisible(); await expect(menu.getByText('Uncommitted changes: 14 files')).toBeVisible()
    await expect(control.getByText('Project agent · permission-controlled')).toHaveCount(0)
    await menu.getByRole('button', { name: /feature\/one/ }).hover(); await expect(menu).toBeVisible()
    const box = await menu.boundingBox(); expect(box!.y).toBeGreaterThanOrEqual(0); expect(box!.y + box!.height).toBeLessThanOrEqual(760)
    await control.screenshot({ path: '/tmp/athena-git-branch-popup.png' })
    await menu.getByRole('button', { name: 'feature/one', exact: true }).click()
    await expect(menu.getByRole('alert')).toContainText('Local changes would be overwritten. Your changes are preserved.')
    expect(git('branch', '--show-current').trim()).toBe('main')
    await expect(menu.getByLabel('Git error details')).toHaveCount(0)
    const collapsed = await menu.boundingBox(); expect(collapsed!.height).toBeLessThan(520)
    await control.screenshot({ path: '/tmp/athena-git-branch-error-compact.png' })
    await menu.getByRole('button', { name: 'Show details' }).click()
    const details = menu.getByLabel('Git error details')
    await expect(details).toContainText(conflictFiles[0])
    expect(await details.evaluate(node => node.scrollHeight > node.clientHeight)).toBe(true)
    const expanded = await menu.boundingBox(); expect(expanded!.height).toBeLessThan(660); expect(expanded!.y).toBeGreaterThanOrEqual(0); expect(expanded!.y + expanded!.height).toBeLessThanOrEqual(760)
    await expect(details).toBeInViewport({ ratio: 1 })
    expect(await menu.evaluate(node => node.scrollHeight <= node.clientHeight + 1)).toBe(true)
    await expect(menu.getByRole('textbox', { name: 'Search branches' })).toBeInViewport()
    await expect(menu.getByRole('button', { name: /Create and switch/ })).toBeInViewport()
    await control.screenshot({ path: '/tmp/athena-git-branch-error-details.png' })
    await menu.getByRole('button', { name: 'Hide details' }).click()
    for (const file of conflictFiles) expect(await readFile(join(project, file), 'utf8')).toBe('preserved local content')
    await menu.getByRole('textbox', { name: 'Search branches' }).fill('two'); await expect(menu.getByRole('button', { name: /feature\/one/ })).toHaveCount(0)
    await menu.getByRole('button', { name: /feature\/two/ }).click(); await expect(control.getByRole('button', { name: 'Git branch: feature/two' })).toBeVisible()
    expect(git('branch', '--show-current').trim()).toBe('feature/two')
    await control.getByRole('button', { name: 'Git branch: feature/two' }).click(); await menu.getByRole('button', { name: /Create and switch/ }).click()
    await control.getByRole('textbox', { name: 'Create and switch to new branch' }).fill('feature/created')
    await control.getByRole('button', { name: 'Create and switch', exact: true }).click()
    await expect(control.getByRole('button', { name: 'Git branch: feature/created' })).toBeVisible()
    expect(git('branch', '--show-current').trim()).toBe('feature/created')
    expect(await readFile(join(project, 'source.txt'), 'utf8')).toBe('preserved dirty content')
    expect(await readFile(join(project, 'untracked.txt'), 'utf8')).toBe('preserved untracked')
    git('switch', 'main'); await expect(control.getByRole('button', { name: 'Git branch: main' })).toBeVisible()
    await app.close(); app = await launch()
    await expect.poll(() => app.windows().some(page => page.url().includes('surface=control'))).toBe(true)
    control = app.windows().find(page => page.url().includes('surface=control'))!
    await control.getByRole('button', { name: 'Conversation', exact: true }).click(); await expect(control.getByRole('button', { name: 'Git branch: main' })).toBeVisible()
  } finally { await app.close(); await rm(profile, { recursive: true, force: true }) }
})
