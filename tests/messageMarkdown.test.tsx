import { fireEvent, render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
const desktopMocks = vi.hoisted(() => ({ copy: vi.fn(async () => ({ ok: true })), openExternalLink: vi.fn(async () => ({ ok: true })) }))
const mermaidMocks = vi.hoisted(() => ({ initialize: vi.fn(), render: vi.fn(async () => ({ svg: '<svg viewBox="0 0 200 100"><text>Diagram</text></svg>' })) }))
vi.mock('../src/services/desktop', () => ({ desktop: { copyChatText: desktopMocks.copy, openExternalLink: desktopMocks.openExternalLink } }))
vi.mock('mermaid', () => ({ default: mermaidMocks }))
import { MessageMarkdown } from '../src/features/chat/MessageMarkdown'
describe('safe chat Markdown', () => {
  it('renders Markdown/code and copies code as inert text', async () => {
    const { container } = render(<MessageMarkdown content={'# Hello\n\n**World**\n\n```ts\nconst answer = 42\n```'} />)
    expect(screen.getByRole('heading', { name: 'Hello' })).toBeVisible()
    expect(screen.getByText('World').tagName).toBe('STRONG')
    expect(screen.getByText('ts')).toBeVisible()
    expect(container.querySelector('.hljs-keyword')).toHaveTextContent('const')
    fireEvent.click(screen.getByRole('button', { name: 'Copy code' }))
    expect(desktopMocks.copy).toHaveBeenCalledWith({ text: 'const answer = 42\n' })
    expect(await screen.findByText('Copied')).toBeVisible()
  })
  it('renders tables, lists, tasks, quotes, inline code and strikethrough', () => {
    const { container } = render(<MessageMarkdown content={'| Name | Value |\n| --- | --- |\n| Item | 42 |\n\n- [x] Done\n- [ ] Next\n\n1. First\n2. Second\n\n> A quote\n\nUse `npm test` and ~~old~~ text.'} />)
    expect(screen.getByRole('table')).toHaveTextContent('Item')
    expect(screen.getByRole('region', { name: 'Scrollable table' })).toHaveAttribute('tabindex', '0')
    expect(screen.getAllByRole('checkbox')[0]).toBeChecked()
    expect(screen.getAllByRole('checkbox')[1]).toBeDisabled()
    expect(container.querySelector('ol')).toHaveTextContent('First')
    expect(container.querySelector('blockquote')).toHaveTextContent('A quote')
    expect(container.querySelector('del')).toHaveTextContent('old')
    expect(screen.getByText('npm test').tagName).toBe('CODE')
  })
  it('omits trailing web Sources appendices from the visible answer', () => {
    const { container } = render(<MessageMarkdown content={'The React release notes describe the latest changes.\n\nSources:\n- [React](https://react.dev/blog) — react.dev; retrieved 2026-10-11T16:48:50.304Z\n- [Research](https://example.com) — example.com; retrieved 2026-10-11T16:48:50.304Z'} />)
    expect(screen.getByText('The React release notes describe the latest changes.')).toBeVisible()
    expect(container.textContent).not.toContain('Sources:')
    expect(container.textContent).not.toContain('retrieved 2026-10-11')
    expect(container.querySelector('.chat-source-link')).toBeNull()
  })
  it('handles unknown languages and unfinished streamed fences without crashing', () => {
    const { rerender } = render(<MessageMarkdown content={'```unlisted-language\n<test>literal</test>'} />)
    expect(screen.getByText('unlisted-language')).toBeVisible()
    expect(screen.getByLabelText('unlisted-language code')).toHaveTextContent('<test>literal</test>')
    rerender(<MessageMarkdown content={'```\nplain text\n```'} />)
    expect(screen.getByLabelText('text code')).toHaveTextContent('plain text')
  })
  it('renders Mermaid in a sandboxed frame with strict security and expandable controls', async () => {
    render(<MessageMarkdown content={'```mermaid\ngraph TD\nA-->B\n```'} />)
    const diagram = await screen.findByTitle('Mermaid diagram')
    expect(diagram).toHaveAttribute('sandbox', '')
    expect(diagram).toHaveAttribute('srcdoc', expect.stringContaining("default-src 'none'"))
    expect(mermaidMocks.initialize).toHaveBeenCalledWith(expect.objectContaining({ securityLevel: 'strict', startOnLoad: false }))
    expect(mermaidMocks.render).toHaveBeenCalledWith(expect.stringMatching(/^athena-mermaid-/), 'graph TD\nA-->B\n')
    fireEvent.click(screen.getByRole('button', { name: 'Expand diagram' }))
    expect(screen.getByRole('button', { name: 'Close expanded diagram' })).toBeVisible()
  })
  it('never creates executable HTML or remote image requests, and routes clicked HTTP links through trusted IPC', () => {
    const { container } = render(<MessageMarkdown content={'<script>alert(1)</script>\n\n<img src="https://evil.example/pixel">\n\n![tracking](https://evil.example/pixel)\n\n[bad](javascript:alert(1))\n\n[site](https://example.com)'} />)
    expect(container.querySelectorAll('script,img,a,iframe')).toHaveLength(0)
    expect(screen.getByText('[Image omitted: tracking]')).toBeVisible()
    const link = screen.getByRole('button', { name: 'Open source link example.com' })
    expect(link).toHaveTextContent('site (example.com)')
    fireEvent.click(link)
    expect(desktopMocks.openExternalLink).toHaveBeenCalledWith({ url: 'https://example.com' })
  })
})
